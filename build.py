"""Build the release binaries.

    python build.py

Produces two executables in dist/:

    stub.exe                    the stand-in process, copied at launch time
    DiscordQuestCompleter.exe   the application, with stub.exe bundled inside

The stub is built first because the main app embeds it as a data file. It is
kept separate, and free of PySide6, so that the file copied into an emulated
game folder stays small.
"""

import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DIST = ROOT / 'dist'
BUILD = ROOT / 'build'
STUB = DIST / 'stub.exe'
ICON = ROOT / 'dqc' / 'data' / 'icon.ico'
APP_NAME = 'DiscordQuestCompleter'


def clear(path: Path) -> None:
    """Delete a build directory, saying plainly why if it cannot be deleted.

    The usual cause is the application still being open, which holds a lock on
    its own executable. Ignoring that failure leaves the stale binary in place
    and PyInstaller fails later with a bare access-denied error.
    """
    if not path.exists():
        return
    try:
        shutil.rmtree(path)
    except OSError as exc:
        sys.exit(
            f'could not clear {path}\n  {exc}\n'
            '  Close DiscordQuestCompleter.exe and any running stub window, '
            'then build again.'
        )


def run(args: list[str]) -> None:
    print('  $', ' '.join(args))
    result = subprocess.run(args, cwd=ROOT)
    if result.returncode != 0:
        sys.exit(f'command failed with exit code {result.returncode}')


def build_stub() -> None:
    print('\n[1/2] building stub.exe')
    run([
        sys.executable, '-m', 'PyInstaller',
        '--noconfirm', '--clean',
        '--onefile', '--windowed',
        '--name', 'stub',
        '--icon', str(ICON),
        # Nothing here should pull in the GUI framework or a HTTP stack.
        '--exclude-module', 'PySide6',
        '--exclude-module', 'shiboken6',
        '--exclude-module', 'requests',
        '--exclude-module', 'urllib3',
        '--exclude-module', 'numpy',
        '--exclude-module', 'unittest',
        '--exclude-module', 'pydoc',
        str(ROOT / 'dqc' / 'stub.py'),
    ])
    if not STUB.is_file():
        sys.exit('stub.exe was not produced')
    print(f'  stub.exe: {STUB.stat().st_size / 1e6:.1f} MB')


def generate_uia_wrapper() -> None:
    """Have comtypes write its UI Automation wrapper into comtypes.gen now,
    so the build can bundle it instead of the frozen app writing it later."""
    import comtypes.client
    comtypes.client.GetModule('UIAutomationCore.dll')


# PyInstaller's Qt Quick hook bundles every QML module PySide6 ships, which
# drags in Qt WebEngine (over 200 MB), Qt 3D, PDF, charts and more. None of
# them are used. Anything bundled under one of these prefixes is dropped.
# Matching is on the start of the path inside the bundle, case-insensitive.
UNUSED_QT = [
    'PySide6/Qt6WebEngine', 'PySide6/QtWebEngine', 'PySide6/qml/QtWebEngine',
    'PySide6/resources/qtwebengine', 'PySide6/translations/qtwebengine',
    'PySide6/Qt6WebView', 'PySide6/qml/QtWebView',
    'PySide6/Qt6WebChannel', 'PySide6/qml/QtWebChannel',
    'PySide6/Qt6Quick3D', 'PySide6/qml/QtQuick3D', 'PySide6/Qt63D', 'PySide6/qml/Qt3D',
    'PySide6/Qt6Pdf', 'PySide6/qml/QtQuick/Pdf',
    'PySide6/Qt6Charts', 'PySide6/qml/QtCharts', 'PySide6/Qt6Graphs', 'PySide6/qml/QtGraphs',
    'PySide6/Qt6DataVisualization', 'PySide6/qml/QtDataVisualization',
    'PySide6/Qt6Multimedia', 'PySide6/qml/QtMultimedia', 'PySide6/Qt6SpatialAudio',
    'PySide6/Qt6Location', 'PySide6/qml/QtLocation',
    'PySide6/Qt6Positioning', 'PySide6/qml/QtPositioning',
    'PySide6/Qt6Sensors', 'PySide6/qml/QtSensors',
    'PySide6/Qt6VirtualKeyboard', 'PySide6/qml/QtQuick/VirtualKeyboard',
    'PySide6/Qt6TextToSpeech', 'PySide6/qml/QtTextToSpeech',
    'PySide6/Qt6Scxml', 'PySide6/qml/QtScxml',
    'PySide6/Qt6StateMachine', 'PySide6/qml/QtQml/StateMachine',
    'PySide6/Qt6RemoteObjects', 'PySide6/qml/QtRemoteObjects',
    'PySide6/Qt6ShaderTools', 'PySide6/Qt6Quick/Scene', 'PySide6/qml/QtQuick/Scene',
    'PySide6/qml/QtQuick/Particles', 'PySide6/Qt6QuickParticles',
    # The interface uses the Basic style only.
    'PySide6/Qt6QuickControls2Imagine', 'PySide6/qml/QtQuick/Controls/Imagine',
    'PySide6/Qt6QuickControls2Material', 'PySide6/qml/QtQuick/Controls/Material',
    'PySide6/Qt6QuickControls2Universal', 'PySide6/qml/QtQuick/Controls/Universal',
    'PySide6/Qt6QuickControls2Fusion', 'PySide6/qml/QtQuick/Controls/Fusion',
    'PySide6/Qt6QuickControls2FluentWinUI3', 'PySide6/qml/QtQuick/Controls/FluentWinUI3',
    # Software OpenGL. Qt Quick draws through Direct3D on Windows.
    'PySide6/opengl32sw.dll',
]

SPEC = '''# Generated by build.py. Edit build.py instead.
UNUSED = [p.lower() for p in {unused!r}]

def keep(entry):
    return not entry[0].replace('\\\\', '/').lower().startswith(tuple(UNUSED))

a = Analysis(
    [{script!r}],
    datas=[({data!r}, 'data'), ({stub!r}, '.'), ({qml!r}, 'ui/qml')],
    hiddenimports=collect_submodules('comtypes.gen'),
    excludes=['tkinter', 'unittest', 'numpy',
              'PySide6.QtWebEngineCore', 'PySide6.Qt3DCore',
              'PySide6.QtMultimedia', 'PySide6.QtCharts'],
)
a.binaries = [e for e in a.binaries if keep(e)]
a.datas = [e for e in a.datas if keep(e)]
pyz = PYZ(a.pure)
exe = EXE(
    pyz, a.scripts, a.binaries, a.datas,
    name={name!r}, icon={icon!r}, console=False, upx=False,
)
'''


def build_app() -> None:
    print('\n[2/2] building the application')
    generate_uia_wrapper()
    BUILD.mkdir(parents=True, exist_ok=True)
    spec = BUILD / f'{APP_NAME}.spec'
    spec.write_text(
        'from PyInstaller.utils.hooks import collect_submodules\n' + SPEC.format(
            unused=UNUSED_QT,
            script=str(ROOT / 'run.py'),
            data=str(ROOT / 'dqc' / 'data'),
            stub=str(STUB),
            qml=str(ROOT / 'dqc' / 'ui' / 'qml'),
            name=APP_NAME,
            icon=str(ICON),
        ),
        encoding='utf-8',
    )
    run([
        sys.executable, '-m', 'PyInstaller',
        '--noconfirm', '--clean',
        '--distpath', str(DIST),
        '--workpath', str(BUILD / 'work'),
        str(spec),
    ])
    app = DIST / f'{APP_NAME}.exe'
    if not app.is_file():
        sys.exit(f'{APP_NAME}.exe was not produced')
    print(f'  {APP_NAME}.exe: {app.stat().st_size / 1e6:.1f} MB')


def main() -> int:
    if not (ROOT / 'dqc' / 'data' / 'detectable.json.gz').is_file():
        sys.exit('missing dqc/data/detectable.json.gz, run tools/build_snapshot.py first')
    if not ICON.is_file():
        sys.exit('missing dqc/data/icon.ico, run tools/make_icon.py first')

    for path in (BUILD, DIST):
        clear(path)

    build_stub()
    build_app()

    print('\ndone. Ship dist/DiscordQuestCompleter.exe')
    return 0


if __name__ == '__main__':
    sys.exit(main())
